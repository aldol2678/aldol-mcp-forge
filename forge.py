NAME_RE = re.compile(r'^[a-z][a-z0-9-]{2,39}$')


def _name(name):
    if not isinstance(name, str) or not NAME_RE.fullmatch(name):
        raise ValueError('project_name must match ^[a-z][a-z0-9-]{2,39}$')
    return name


def _path(name):
    return PROJECTS / _name(name)


def _hash(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _preview(a):
    description = a['description'].strip()
    if not description or len(description) > 2000:
        raise ValueError('description must contain 1..2000 characters')
    template = select_template(description)
    return {'supported': template is not None, 'template': template,
            'capabilities': TEMPLATE_INFO.get(template),
            'note': 'Only three curated, read-only templates supported. No arbitrary code generation.'}


def _render_server(name, version, selected):
    # No user-provided text enters generated executable source except a validated slug.
    lines = [
        '"""Generated by ALDOL MCP Forge; run with MCP Python SDK v2."""',
        'import sys',
        'from typing import Any',
        'from templates import get_tool, html_audit as _html_audit, json_audit as _json_audit, text_stats as _text_stats',
        '',
        'if __name__ == "__main__" and "--compat-smoke-test" in sys.argv:',
        '    from mcp_runtime import serve',
        f'    serve({json.dumps(name)}, {json.dumps(version)}, [get_tool(t) for t in {selected!r}])',
        'else:',
        '    from mcp.server import MCPServer',
        f'    app = MCPServer({json.dumps(name)})',
    ]
    for template in selected:
        lines += [
            '    @app.tool()',
            f'    def {template}(content: str) -> dict[str, Any]:',
            f'        """{TEMPLATE_INFO[template]}"""',
            f'        return _{template}({{"content": content}})',
            '',
        ]
    lines += ['    if __name__ == "__main__":', '        app.run()', '']
    return '\n'.join(lines)


def _readme(name, description, selected):
    return f'''# {name}

Generated by **ALDOL MCP Forge v0.2**. This server uses official Python SDK v2.

- Original request: {description}
- Tools: {', '.join(selected)}
- Local stdio transport; read-only tool handlers. No deployment performed.

## Install / run

Requires Python >=3.11. From inside this directory:

```sh
python -m pip install -r requirements.txt
python server.py
```

Example local MCP client configuration (replace absolute path):

```json
{{"mcpServers":{{"{name}":{{"command":"python3","args":["/ABSOLUTE/PATH/{name}/server.py"]}}}}}}
```

Each tool accepts a `content` string (max 220000 characters). Tool handlers perform no network requests.

## Testing and trust

The `--compat-smoke-test` option is **only** for the Forge offline transport smoke-test.
It uses a legacy, limited JSON-RPC implementation, **not** the official SDK.
Install requirements and validate with your real MCP client/Inspector before production use.
The Linux namespace test, when supported, denies networking and mounts the project read-only,
but does not hide other host files and is not a complete security sandbox.
''' 


def _write_project(target, name, description, selected, previous=None):
    version = ('0.2.' + str(int(previous['version'].split('.')[-1]) + 1)
               if previous is not None and previous['version'].startswith('0.2.') else '0.2.0')
    for item in ('mcp_runtime.py', 'templates.py'):
        shutil.copyfile(ROOT / item, target / item)
    (target / 'server.py').write_text(_render_server(name, version, selected), encoding='utf-8')
    (target / 'requirements.txt').write_text('mcp>=2,<3\n', encoding='utf-8')
    manifest = {
        'name': name, 'version': version, 'forge_version': '0.2.0',
        'description': description, 'templates': selected,
        'created_at': datetime.now(timezone.utc).isoformat(),
        'files_sha256': {n: _hash(target / n) for n in (*SOURCES, 'requirements.txt')},
    }
    if previous is not None:
        manifest['previous_version'] = previous['version']
        manifest['previous_manifest_sha256'] = previous['_manifest_hash']
    (target / 'manifest.json').write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    (target / 'README.md').write_text(_readme(name, description, selected), encoding='utf-8')
    return manifest


def _validated(name):
    folder = _path(name)
    if not folder.is_dir() or folder.is_symlink():
        raise ValueError('Project does not exist or is symlink')
    manifest_path = folder / 'manifest.json'
    if not manifest_path.is_file() or manifest_path.is_symlink():
        raise ValueError('missing or unsafe project manifest')
    raw = manifest_path.read_bytes()
    manifest = json.loads(raw)
    if manifest.get('name') != name:
        raise ValueError('manifest identity mismatch')
    legacy = manifest.get('version') == '0.1.0' and 'template' in manifest
    selected = [manifest['template']] if legacy else manifest.get('templates')
    if (not isinstance(selected, list) or not selected or len(selected) != len(set(selected))
            or any(t not in TEMPLATE_INFO for t in selected)):
        raise ValueError('invalid tools manifest')
    hashes = manifest.get('files_sha256') or {}
    allowed = set((*SOURCES, 'manifest.json', 'README.md', *((() if legacy else ('requirements.txt',)))))
    if {p.name for p in folder.iterdir()} != allowed:
        raise ValueError('Unexpected or missing project files')
    for filename in (*SOURCES, *(() if legacy else ('requirements.txt',))):
        p = folder / filename
        if not p.is_file() or p.is_symlink() or hashes.get(filename) != _hash(p):
            raise ValueError('source checksum mismatch or unsafe file: ' + filename)
        if filename in ('mcp_runtime.py', 'templates.py') and p.read_bytes() != (ROOT / filename).read_bytes():
            raise ValueError('source differs from curated template: ' + filename)
    if legacy:
        expected = ('from mcp_runtime import serve\nfrom templates import get_tool\n'
                    f'serve({json.dumps(name)}, "0.1.0", [get_tool({json.dumps(selected[0])})])\n')
    else:
        if not re.fullmatch(r'0\.2\.[0-9]+', manifest.get('version', '')) or manifest.get('forge_version') != '0.2.0':
            raise ValueError('unsupported project version')
        expected = _render_server(name, manifest['version'], selected)
        if (folder / 'requirements.txt').read_text(encoding='utf-8') != 'mcp>=2,<3\n':
            raise ValueError('requirements altered')
    if (folder / 'server.py').read_text(encoding='utf-8') != expected:
        raise ValueError('source does not match approved generator output')
    manifest['_manifest_hash'] = hashlib.sha256(raw).hexdigest()
    return folder, manifest, selected


def _project_lock(operation):
    @wraps(operation)
    def wrapper(a):
        name = _name(a['project_name'])
        lockroot = PROJECTS / '.locks'
        lockroot.mkdir(parents=True, exist_ok=True)
        lock = lockroot / name
        try:
            lock.mkdir()
        except FileExistsError as exc:
            raise RuntimeError('Project is locked by another operation; concurrent mutation refused') from exc
        try:
            return operation(a)
        finally:
            lock.rmdir()
    return wrapper


@_project_lock
def _create(a):
    name = _name(a['project_name'])
    description = a['description'].strip()
    resolved = _preview({'description': description})
    if not resolved['supported']:
        raise ValueError('Unsupported request. Allowed templates: HTML, JSON, text statistics.')
    PROJECTS.mkdir(parents=True, exist_ok=True)
    dest = _path(name)
    if dest.exists() or dest.is_symlink():
        raise ValueError('Project exists; refusing overwrite')
    temp = Path(tempfile.mkdtemp(prefix='.forge-', dir=PROJECTS))
    try:
        _write_project(temp, name, description, [resolved['template']])
        temp.rename(dest)
    finally:
        if temp.exists():
            shutil.rmtree(temp)
    return {'created': True, 'project_name': name, 'tools': [resolved['template']],
            'path': str(dest), 'official_sdk_code': True, 'auto_deployed': False}


def _probe(folder, expected_name, selected, isolation='auto'):
    samples = {
        'html_audit': '<html lang="ko"><head><title>T</title><meta name="viewport" content="width=device-width"></head><body><canvas></canvas></body></html>',
        'json_audit': '{"hello":"world"}',
        'text_stats': '안녕 Forge',
    }
    messages = [
        {'jsonrpc': '2.0', 'id': 1, 'method': 'initialize', 'params': {'protocolVersion': '2026-07-28', 'capabilities': {}, 'clientInfo': {'name': 'forge-smoke', 'version': '0.2'}}},
        {'jsonrpc': '2.0', 'method': 'notifications/initialized', 'params': {}},
        {'jsonrpc': '2.0', 'id': 2, 'method': 'tools/list', 'params': {}},
    ]
    for index, t in enumerate(selected):
        messages += [
            {'jsonrpc': '2.0', 'id': 10 + 2 * index, 'method': 'tools/call', 'params': {'name': t, 'arguments': {'content': samples[t]}}},
            {'jsonrpc': '2.0', 'id': 11 + 2 * index, 'method': 'tools/call', 'params': {'name': t, 'arguments': {'content': 123}}},
        ]
    messages.append({'jsonrpc': '2.0', 'id': 100, 'method': 'ping', 'params': {}})
    payload = ''.join(json.dumps(row, ensure_ascii=False) + '\n' for row in messages)
    stdout, isolation_used = run_server(folder, payload, isolation=isolation)
    try:
        responses = [json.loads(line) for line in stdout.splitlines() if line.strip()]
    except json.JSONDecodeError as exc:
        raise RuntimeError('Non-JSON stdout from generated server') from exc
    byid = {msg['id']: msg for msg in responses}
    listed = [x['name'] for x in byid.get(2, {}).get('result', {}).get('tools', [])]
    checks = {'server_identity': byid.get(1, {}).get('result', {}).get('serverInfo', {}).get('name') == expected_name,
              'list_matches': listed == selected,
              'ping': byid.get(100, {}).get('result') == {},
              'notification_silent': len(responses) == 3 + 2 * len(selected)}
    results = {}
    for index, t in enumerate(selected):
        success = byid.get(10 + 2 * index, {}).get('result', {})
        failure = byid.get(11 + 2 * index, {}).get('result', {})
        checks[f'{t}_call'] = success.get('isError') is not True and len(success.get('content', [])) > 0
        checks[f'{t}_invalid_rejected'] = failure.get('isError') is True
        if checks[f'{t}_call']:
            results[t] = json.loads(success['content'][0]['text'])
    if not all(checks.values()):
        raise RuntimeError(f'Compatibility smoke test failed: {checks}')
    return checks, results, isolation_used



