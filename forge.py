def _write_openapi_project(dest, name, parsed, spec_json):
    version = '0.3.0'
    for src in ('mcp_runtime.py', 'api_runtime.py'):
        shutil.copyfile(ROOT / src, dest / src)
    (dest / 'server.py').write_text(render_api_server(name, version, parsed['operations']), encoding='utf-8')
    (dest / 'operations.py').write_text(render_operations(parsed['operations']), encoding='utf-8')
    (dest / 'requirements.txt').write_text('mcp>=2,<3\n', encoding='utf-8')
    (dest / 'openapi.json').write_text(spec_json, encoding='utf-8')
    (dest / 'README.md').write_text(api_readme(name, parsed), encoding='utf-8')
